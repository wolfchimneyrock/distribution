#!/usr/bin/env python3
"""gen_oc.py <base.dtb> <name> <gpu_mV> <big_mV|0> <lit_mV|0>: a ROCKNIX overclock overlay for an RK3588 vendor-kernel
DTB. The top OPP of each table (GPU 1 GHz; A76 2256-2400 MHz, every bin's top; A55 1.8 GHz) gets the new voltage on
every PVTM level (PVTPLL then clocks higher). Every OPP of the table keeps its targets, but its max cells are raised
to at least the new voltage: the core ("vdd") and its memory supply ("mem") share one regulator, and when their
ranges stop overlapping the kernel refuses the step down (-EINVAL, "failed to set voltage"). The regulators' max goes
up to match. Writes <name>.dts next to this script; prints a check."""
import re, subprocess, sys

dtb, name, gpu, big, lit = sys.argv[1], sys.argv[2], *map(int, sys.argv[3:6])
src = subprocess.run(["dtc", "-q", "-I", "dtb", "-O", "dts", dtb], capture_output=True, text=True, check=True).stdout
syms = dict(re.findall(r'^\t\t(\w+) = "([^"]+)";', src.split("__symbols__ {", 1)[1], re.M))

def node_body(path):
    """Text of the node at path (top-level children of / only, as these tables are)."""
    nm = path.strip("/").split("/")[-1]
    m = re.search(r"^\t" + re.escape(nm) + r" \{\n(.*?)^\t\};", src, re.M | re.S)
    return m.group(1)

def opps(path):
    body = node_body(path)
    for m in re.finditer(r"^\t\t(opp-[\w-]+) \{\n(.*?)^\t\t\};", body, re.M | re.S):
        props = dict(re.findall(r"^\t\t\t(opp-microvolt[\w-]*) = <([^>]*)>;", m.group(2), re.M))
        yield m.group(1), {k: [int(x, 16) for x in v.split()] for k, v in props.items()}

TABLES = []  # (label, new top uV, top OPP names, regulator labels, new regulator max uV)
if gpu: TABLES.append(("gpu_opp_table", gpu * 1000, {"opp-1000000000"}, ["vdd_gpu_s0"], gpu * 1000))
if big:
    for t in ("cluster1_opp_table", "cluster2_opp_table"):
        TABLES.append((t, big * 1000, {"opp-2256000000", "opp-2304000000", "opp-2352000000", "opp-2400000000"},
                       ["vdd_cpu_big0_s0", "vdd_cpu_big1_s0"], max(big * 1000, 1050000)))
if lit: TABLES.append(("cluster0_opp_table", lit * 1000, {"opp-1800000000"}, ["vdd_cpu_lit_s0"], max(lit * 1000, 950000)))

out = ["/dts-v1/;", "/plugin/;", "",
       f"// RK3588 (ROCK 5B, vendor kernel) overclock: GPU 1 GHz OPP {gpu} mV" + (f", A76 top OPPs {big} mV" if big else "")
       + (f", A55 1.8 GHz OPP {lit} mV" if lit else "") + ".",
       "// PVTPLL sets the real clocks from the voltage. Tested stable on one ROCK 5B (GPU PVTM level 5, A76 levels 6/7,",
       "// A55 level 6) with glmark2 / all-core self-checking stress. Other chips (bins) may differ: if it does not boot,",
       "// remove the FDTOVERLAYS line from extlinux/extlinux.conf on the boot partition from a PC.",
       "// Generated by gen_oc.py from the kernel's rk3588-rock-5b.dtb; every OPP's max is raised so that the core and",
       "// memory supplies (one regulator) can always step down.", ""]
check, regs = [], {}
for label, top, tops, rlabels, rmax in TABLES:
    out.append(f"&{label} {{")
    for opp, props in opps(syms[label]):
        if not props: continue
        out.append(f"\t{opp} {{")
        for p, v in props.items():
            trip = [v[i:i + 3] for i in range(0, len(v), 3)]
            if opp in tops: trip = [[top, top, top] for _ in trip]
            else: trip = [[a, b, max(c, top)] for a, b, c in trip]
            out.append(f"\t\t{p} = <{' '.join(str(x) for t in trip for x in t)}>;")
            check.append((label, opp, p, trip))
        out.append("\t};")
    out.append("};")
    for r in rlabels: regs[r] = max(regs.get(r, 0), rmax)
for r, mx in regs.items(): out.append(f"&{r} {{ regulator-max-microvolt = <{mx}>; }};")
open(f"{name}.dts", "w").write("\n".join(out) + "\n")
bad = [c for c in check if any(t[2] < t[0] for t in c[3])]
print(f"{name}: {len(check)} microvolt properties, regulators {regs}, inconsistent {len(bad)}")
